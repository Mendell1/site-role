  for select using (auth.uid() = usuario_id);


-- ============================================================
-- 4. NOTIFICAÇÕES
-- ============================================================
create table if not exists public.notificacoes (
  id           uuid primary key default gen_random_uuid(),
  usuario_id   uuid not null references public.perfis(id) on delete cascade,
  titulo       text not null,
  mensagem     text not null,
  denuncia_id  uuid references public.denuncias(id) on delete cascade,
  lida         boolean not null default false,
  criado_em    timestamptz not null default now()
);

create index if not exists notificacoes_usuario_idx
  on public.notificacoes (usuario_id, lida, criado_em desc);

alter table public.notificacoes enable row level security;

-- cada um vê e marca como lida apenas as suas
drop policy if exists notif_ler on public.notificacoes;
create policy notif_ler on public.notificacoes
  for select using (auth.uid() = usuario_id);

drop policy if exists notif_marcar on public.notificacoes;
create policy notif_marcar on public.notificacoes
  for update using (auth.uid() = usuario_id) with check (auth.uid() = usuario_id);

drop policy if exists notif_apagar on public.notificacoes;
create policy notif_apagar on public.notificacoes
  for delete using (auth.uid() = usuario_id);


-- ------------------------------------------------------------
-- 4.1 Toda mudança de status avisa quem denunciou
-- O gatilho é SECURITY DEFINER porque quem muda o status é o
-- administrador, mas a notificação pertence a outra pessoa.
-- ------------------------------------------------------------
create or replace function public.notificar_status_denuncia()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  texto text;
begin
  if new.status is not distinct from old.status then
    return new;
  end if;

  if new.status = 'finalizada' then
    new.finalizada_em := now();
  elsif old.status = 'finalizada' then
    new.finalizada_em := null;        -- voltou atrás, o prazo reinicia
  end if;

  texto := case new.status
    when 'em_analise' then 'Sua denúncia está sendo analisada pela moderação.'
    when 'finalizada' then 'Sua denúncia foi analisada e finalizada. Obrigado por avisar.'
    when 'arquivada'  then 'Sua denúncia foi arquivada sem providências.'
    else 'Sua denúncia foi recebida e entrou na fila de análise.'
  end;

  if new.resposta is not null and length(trim(new.resposta)) > 0 then
    texto := texto || ' Resposta da moderação: ' || new.resposta;
  end if;

  if new.usuario_id is not null then
    insert into public.notificacoes (usuario_id, titulo, mensagem, denuncia_id)
    values (new.usuario_id, 'Denúncia nº ' || new.numero, texto, new.id);
  end if;

  return new;
end;
$$;

drop trigger if exists ao_mudar_status_denuncia on public.denuncias;
create trigger ao_mudar_status_denuncia
  before update on public.denuncias
  for each row execute function public.notificar_status_denuncia();


-- ============================================================
-- 5. LIMPEZA AUTOMÁTICA (7 dias após finalizar)
--
-- A função é chamada pelo painel sempre que o administrador
-- abre a área de denúncias. Se o seu projeto tiver pg_cron,
-- dá para agendar — o comando está comentado no fim.
-- ============================================================
create or replace function public.limpar_denuncias_antigas()
returns integer
language plpgsql
security definer set search_path = public
as $$
declare
  apagadas integer;
begin
  delete from public.denuncias
  where status = 'finalizada'
    and finalizada_em is not null
    and finalizada_em < now() - interval '7 days';

  get diagnostics apagadas = row_count;
  return apagadas;
end;
$$;

grant execute on function public.limpar_denuncias_antigas() to authenticated;

