-- ============================================================
-- 1. EXCLUSÃO DA PRÓPRIA CONTA
--
-- O navegador não pode apagar de auth.users: a chave anon não
-- tem esse poder, e é bom que não tenha. A saída é uma função
-- SECURITY DEFINER, que roda com os privilégios de quem a criou
-- mas só apaga a linha de quem chamou — auth.uid() não pode ser
-- forjado pelo cliente.
--
-- Como perfis referencia auth.users com ON DELETE CASCADE,
-- eventos, comentários, favoritos e interesses vão junto.
-- ============================================================
create or replace function public.excluir_minha_conta()
returns void
language plpgsql
security definer set search_path = public, auth
as $$
declare
  eu uuid := auth.uid();
begin
  if eu is null then
    raise exception 'Nenhuma sessão ativa';
  end if;

  delete from auth.users where id = eu;
end;
$$;

revoke all on function public.excluir_minha_conta() from public, anon;
grant execute on function public.excluir_minha_conta() to authenticated;


-- ============================================================
-- 2. ACEITE DAS REGRAS DE CONVIVÊNCIA
-- ============================================================
alter table public.perfis
  add column if not exists aceitou_regras     boolean not null default false,
  add column if not exists regras_aceitas_em  timestamptz;

create or replace function public.criar_perfil()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  aceite boolean := coalesce((new.raw_user_meta_data->>'aceitou_regras')::boolean, false);
begin
  insert into public.perfis (id, nome, email, data_nascimento, aceitou_regras, regras_aceitas_em)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'nome', split_part(new.email,'@',1)),
    new.email,
    nullif(new.raw_user_meta_data->>'data_nascimento','')::date,
    aceite,
    case when aceite then now() end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;


