-- ============================================================
-- 6. VIEW DAS DENÚNCIAS
-- Traz nome de quem denunciou e do evento, para o painel poder
-- pesquisar por qualquer um deles numa consulta só.
-- ============================================================
drop view if exists public.denuncias_lista;

create view public.denuncias_lista
with (security_invoker = true) as
select
  d.id, d.numero, d.evento_id, d.usuario_id,
  d.motivo, d.descricao, d.status, d.resposta,
  d.criado_em, d.finalizada_em,
  e.nome  as evento_nome,
  e.ativo as evento_ativo,
  p.nome  as autor_nome,
  p.email as autor_email,
  case
    when d.status = 'finalizada' and d.finalizada_em is not null
    then greatest(0, 7 - extract(day from now() - d.finalizada_em)::int)
  end as dias_ate_remocao
from public.denuncias d
left join public.eventos e on e.id = d.evento_id
left join public.perfis  p on p.id = d.usuario_id;

grant select on public.denuncias_lista to authenticated;


